"""
Custom VMS — Hikvision + Dahua, from 0.
FastAPI + SQLite. Camera account login -> RTSP -> go2rtc -> browser.

Run:  python app.py   (http://127.0.0.1:8000)
Env:  VMS_ADMIN_USER, VMS_ADMIN_PASS, SECRET_KEY, GO2RTC_CONFIG
"""
import hashlib
import hmac
import json
import os
import secrets
import sqlite3
import urllib.parse
from pathlib import Path

from fastapi import FastAPI, HTTPException, Request
from fastapi.responses import FileResponse
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel, Field

BASE = Path(__file__).resolve().parent.parent
DATA = BASE / "data"
DATA.mkdir(exist_ok=True)
DB = DATA / "vms.db"
GO2RTC_CONFIG = Path(os.environ.get("GO2RTC_CONFIG", str(DATA / "go2rtc.yaml")))
FRONTEND = BASE / "frontend"

ADMIN_USER = os.environ.get("VMS_ADMIN_USER", "installer")
ADMIN_PASS = os.environ.get("VMS_ADMIN_PASS", "change-me-now")
SECRET = os.environ.get("SECRET_KEY", "dev-secret-change-me").encode()
SESSIONS: dict[str, str] = {}  # token -> username


def rtsp_url(brand: str, host: str, port: int, channel: int,
             username: str, password: str, main: bool = True) -> str:
    """Build the RTSP URL for a brand. Password is URL-encoded."""
    user = urllib.parse.quote(username, safe="")
    pw = urllib.parse.quote(password, safe="")
    if brand == "hikvision":
        # 101 = ch1 main, 102 = ch1 sub, 201 = ch2 main
        code = channel * 100 + (1 if main else 2)
        return f"rtsp://{user}:{pw}@{host}:{port}/Streaming/Channels/{code}"
    if brand == "dahua":
        # subtype=0 main, subtype=1 sub
        sub = 0 if main else 1
        return (f"rtsp://{user}:{pw}@{host}:{port}"
                f"/cam/realmonitor?channel={channel}&subtype={sub}")
    raise ValueError(f"unknown brand: {brand}")


def db():
    con = sqlite3.connect(DB)
    con.row_factory = sqlite3.Row
    con.execute("""CREATE TABLE IF NOT EXISTS cameras(
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        name TEXT NOT NULL, brand TEXT NOT NULL,
        host TEXT NOT NULL, port INTEGER NOT NULL,
        channel INTEGER NOT NULL DEFAULT 1,
        username TEXT NOT NULL, password TEXT NOT NULL,
        conn TEXT NOT NULL DEFAULT 'device',
        cloud_user TEXT DEFAULT '', created TEXT DEFAULT '')""")
    con.execute("""CREATE TABLE IF NOT EXISTS users(
        username TEXT PRIMARY KEY, pw_hash TEXT NOT NULL, role TEXT NOT NULL)""")
    return con


def hash_pw(pw: str) -> str:
    return hashlib.sha256((pw + "vms-salt").encode()).hexdigest()


def write_go2rtc_config() -> int:
    """Regenerate go2rtc.yaml from the DB. Returns camera count."""
    con = db()
    rows = con.execute("SELECT * FROM cameras WHERE conn='device'").fetchall()
    con.close()
    lines = ["# generated by custom-vms — do not edit by hand",
             "# credentials live here, file must stay mode 600",
             "streams:"]
    for r in rows:
        url = rtsp_url(r["brand"], r["host"], r["port"], r["channel"],
                       r["username"], r["password"], main=True)
        sub = rtsp_url(r["brand"], r["host"], r["port"], r["channel"],
                       r["username"], r["password"], main=False)
        lines.append(f"  cam{r['id']}: [{url}, {sub}]")
    GO2RTC_CONFIG.write_text("\n".join(lines) + "\n")
    try:
        os.chmod(GO2RTC_CONFIG, 0o600)
    except OSError:
        pass
    return len(rows)


app = FastAPI(title="Custom VMS — Hik + Dahua")


class Login(BaseModel):
    username: str
    password: str


class CameraIn(BaseModel):
    name: str
    brand: str = Field(pattern="^(hikvision|dahua)$")
    host: str
    port: int = 554
    channel: int = 1
    username: str
    password: str
    conn: str = "device"  # device | cloud (cloud = v2, stored only)


def require_auth(req: Request) -> str:
    token = req.headers.get("Authorization", "").removeprefix("Bearer ").strip()
    if token in SESSIONS:
        return SESSIONS[token]
    raise HTTPException(401, "login required")


def go2rtc_base(req: Request) -> str:
    """go2rtc runs on the same host as this API, port 1984.
    Override with GO2RTC_PUBLIC_URL, e.g. https://vms.example.com:1984"""
    env = os.environ.get("GO2RTC_PUBLIC_URL", "").strip()
    if env:
        return env.rstrip("/")
    host = (req.headers.get("host") or "localhost:8000").split(":")[0]
    return f"http://{host}:1984"


def play_urls(req: Request, stream: str) -> dict:
    """Play URLs for one go2rtc stream. No camera password anywhere here."""
    base = go2rtc_base(req)
    return {
        "stream": stream,
        "go2rtc_ui": f"{base}/",
        "webrtc": f"{base}/api/webrtc?src={stream}",
        "hls": f"{base}/api/stream.m3u8?src={stream}",
        "snapshot": f"{base}/api/frame.jpeg?src={stream}",
    }


def camera_public(req: Request, row: sqlite3.Row) -> dict:
    """What a logged-in account may see for a camera — never password/RTSP."""
    d = dict(row)
    d.pop("password", None)
    d.pop("username", None)
    stream = f"cam{d['id']}"
    d["stream"] = stream
    d["play"] = play_urls(req, stream)
    return d


@app.on_event("startup")
def startup():
    con = db()
    if not con.execute("SELECT 1 FROM users WHERE username=?",
                       (ADMIN_USER,)).fetchone():
        con.execute("INSERT INTO users VALUES (?,?,?)",
                    (ADMIN_USER, hash_pw(ADMIN_PASS), "installer"))
        con.commit()
    con.close()
    write_go2rtc_config()


@app.post("/api/login")
def login(body: Login):
    con = db()
    row = con.execute("SELECT * FROM users WHERE username=?",
                      (body.username,)).fetchone()
    con.close()
    if not row or not hmac.compare_digest(row["pw_hash"], hash_pw(body.password)):
        raise HTTPException(401, "wrong username or password")
    token = secrets.token_urlsafe(32)
    SESSIONS[token] = body.username
    return {"token": token, "user": body.username, "role": row["role"]}


@app.get("/api/me")
def me(req: Request):
    """Who is logged in — use this to check your token works."""
    user = require_auth(req)
    con = db()
    row = con.execute("SELECT username, role FROM users WHERE username=?",
                      (user,)).fetchone()
    con.close()
    return {"user": user, "role": row["role"] if row else "installer"}


@app.get("/api/cameras")
def list_cameras(req: Request):
    """All cameras visible to the logged-in account, with play URLs.
    Never returns camera passwords or RTSP URLs."""
    require_auth(req)
    con = db()
    rows = con.execute(
        "SELECT id,name,brand,host,port,channel,conn FROM cameras ORDER BY id"
    ).fetchall()
    con.close()
    return [camera_public(req, r) for r in rows]


@app.get("/api/cameras/{cid}/stream")
def camera_stream(cid: int, req: Request):
    """One camera + its play URLs for the logged-in account."""
    require_auth(req)
    con = db()
    row = con.execute(
        "SELECT id,name,brand,host,port,channel,conn FROM cameras WHERE id=?",
        (cid,)).fetchone()
    con.close()
    if not row:
        raise HTTPException(404, "camera not found")
    return camera_public(req, row)


@app.get("/api/streams")
def list_streams(req: Request):
    """Flat stream list — the simplest API for another app / player.
    Each entry: camera + go2rtc stream name + webrtc/hls/snapshot URLs."""
    require_auth(req)
    con = db()
    rows = con.execute(
        "SELECT id,name,brand,host,port,channel,conn FROM cameras ORDER BY id"
    ).fetchall()
    con.close()
    return [{"camera_id": r["id"], "name": r["name"], "brand": r["brand"],
             **play_urls(req, f"cam{r['id']}")} for r in rows]


@app.post("/api/cameras")
def add_camera(body: CameraIn, req: Request):
    require_auth(req)
    if body.conn == "cloud":
        raise HTTPException(400, "cloud login is Phase 3 (Hik first) — use device login for now")
    # Validate the RTSP URL builds (no network call here — camera may be remote)
    rtsp_url(body.brand, body.host, body.port, body.channel,
             body.username, body.password)
    con = db()
    cur = con.execute(
        "INSERT INTO cameras(name,brand,host,port,channel,username,password,conn)"
        " VALUES (?,?,?,?,?,?,?,?)",
        (body.name, body.brand, body.host, body.port, body.channel,
         body.username, body.password, body.conn))
    con.commit()
    cid = cur.lastrowid
    con.close()
    n = write_go2rtc_config()
    return {"id": cid, "go2rtc_streams": n,
            "note": "restart go2rtc to pick up the new stream (docker compose restart go2rtc)"}


@app.delete("/api/cameras/{cid}")
def delete_camera(cid: int, req: Request):
    require_auth(req)
    con = db()
    con.execute("DELETE FROM cameras WHERE id=?", (cid,))
    con.commit()
    con.close()
    write_go2rtc_config()
    return {"deleted": cid}


@app.get("/api/go2rtc")
def go2rtc_info(req: Request):
    require_auth(req)
    return {"config": str(GO2RTC_CONFIG), "ui": "http://<server-ip>:1984",
            "note": "streams are cam<id>, e.g. cam1 — play via go2rtc WebRTC/MSE"}


app.mount("/", StaticFiles(directory=FRONTEND, html=True), name="frontend")


if __name__ == "__main__":
    import uvicorn
    uvicorn.run(app, host="0.0.0.0", port=8000)
